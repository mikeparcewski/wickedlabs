// The lab's data export: data/products.json and data/capabilities.json, generated from the page's own COMP and ROWS
// (index.html), so the two can never say different things. wickedagile.com reads both at build time
// (wickedagile src/lib/sources.mjs: labProducts, labCapabilities) for its Work cards; without them it falls back to
// the copy it last served, then to its committed seed, and its versions freeze.
//
//   node tests/export-data.mjs          write both files
//   node tests/export-data.mjs --check  exit 1 when a committed file differs from the export (CI runs this via the spec)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const LAB = 'https://wickedlabs.ai/';
/** a product's view on the lab: the page routes by hash (`#/<id>`); a path under it is GitHub Pages' 404 */
export const labHref = (id) => `${LAB}#/${id}`;

/** COMP, ROWS and the page constants beside them, read from index.html's data block (it holds data and pure
 *  function declarations only, so it evaluates without a DOM) */
export function pageData(html = readFileSync(ROOT + 'index.html', 'utf8')) {
  const start = html.indexOf('var BANDS=');
  const end = html.indexOf('/* map nodes */', start);
  if (start < 0 || end < 0) throw new Error('index.html: the data block (var BANDS= … /* map nodes */) is not where the export expects it');
  const ctx = {};
  vm.runInNewContext(html.slice(start, end) + '\n;this.out={COMP:COMP,ROWS:ROWS,PLATFORM_BADGE:PLATFORM_BADGE,EXPERIMENT:EXPERIMENT,HOODLINE:HOODLINE};', ctx);
  return ctx.out;
}

// the Work cards' short descriptor per product (wickedagile's seed, the approved v3 copy) and where each line comes from
const CARD = {
  studio: { tag: 'the ADE: agentic development environment', expansion: 'agentic development environment' },
  crew: { tag: 'runs and checks jobs' },
  garden: { tag: 'skills and tools' },
  estate: { tag: 'what agents know' },
};
const HOOD_ORDER = ['core', 'bus', 'interactive'];
const HOOD_REF = {
  core: 'wicked-core README (bold line, first clause)',
  bus: 'wicked-bus README (bold line)',
  interactive: 'wicked-interactive README (opening line)',
};
const START_LINE = 'It installs the products you pick, for the coding CLIs you use.';
// relations between the products, each grounded in a capability row the page carries
const RELATIONS = [
  { a: 'crew', b: 'studio', sentence: 'wicked-crew ships wicked-studio as its UI', ref: 'lab products.json: studio via wicked-crew (wicked-crew serve bundles studio)' },
  { a: 'garden', b: 'crew', sentence: 'wicked-garden supplies the skills every agent in a wicked-crew job follows', ref: 'lab capabilities.json row GW', row: 'GW' },
  { a: 'garden', b: 'estate', sentence: 'wicked-garden reads wicked-estate’s code graph', ref: 'lab capabilities.json row G2', row: 'G2' },
];

export function exportData(d = pageData()) {
  const { COMP, ROWS, PLATFORM_BADGE, EXPERIMENT, HOODLINE } = d;
  const byId = Object.fromEntries(COMP.map((c) => [c.id, c]));
  const asOf = COMP.map((c) => c.date).sort().pop();
  const products = COMP.filter((c) => c.tier === 'featured' || c.tier === 'component').map((c) => {
    const card = CARD[c.id];
    if (!card) throw new Error(`no Work card descriptor for ${c.id}`);
    return {
      id: c.id, name: c.name, tier: c.tier,
      ...(c.eyebrow ? { eyebrow: c.eyebrow } : {}),
      ...(card.expansion ? { expansion: card.expansion } : {}),
      tag: card.tag, ver: c.ver, release: c.tag, headline: c.headline, url: labHref(c.id),
    };
  });
  products.push({ id: 'platform', name: EXPERIMENT.name, tier: 'featured', experiment: true, eyebrow: EXPERIMENT.eyebrow });
  const underTheHood = HOOD_ORDER.map((id) => {
    const c = byId[id];
    if (!c || c.tier !== 'hood') throw new Error(`${id} is not under the hood on the page`);
    return { id, name: c.name, line: HOODLINE[id], release: c.tag, ref: HOOD_REF[id] };
  });
  const inst = byId.installer;
  const getStarted = {
    cmd: inst.install, release: inst.tag, ref: 'wicked-installer README (Quick start)', line: START_LINE,
    lineRef: `wicked-installer README at ${inst.tag}, Quick start: pick a bundle or select products individually; it detects which AI coding CLIs you have installed`,
  };
  const rowIds = new Set(ROWS.map((r) => r[0]));
  const relations = RELATIONS.map(({ row, ...r }) => {
    if (row && !rowIds.has(row)) throw new Error(`relation ${r.a}-${r.b} cites row ${row}, which the page no longer has`);
    return r;
  });
  const gen = 'Generated by tests/export-data.mjs from index.html (COMP, ROWS); edit the page, then run it.';
  return {
    products: { $comment: gen, asOf, platformBadge: PLATFORM_BADGE, products, underTheHood, getStarted, relations },
    capabilities: {
      $comment: gen, asOf,
      capabilities: ROWS.map((r) => ({ id: r[0], component: r[1], line: r[2], status: r[5] === 'soon' ? 'soon' : 'released' })),
    },
  };
}

export const FILES = { products: 'data/products.json', capabilities: 'data/capabilities.json' };
export const serialise = (o) => JSON.stringify(o, null, 1) + '\n';

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = exportData();
  const check = process.argv.includes('--check');
  let drift = 0;
  for (const [k, f] of Object.entries(FILES)) {
    const want = serialise(out[k]);
    if (check) {
      let have = null;
      try { have = readFileSync(ROOT + f, 'utf8'); } catch { /* missing */ }
      if (have !== want) { drift++; console.error(`${f} differs from the export: run node tests/export-data.mjs`); }
    } else {
      mkdirSync(ROOT + 'data', { recursive: true });
      writeFileSync(ROOT + f, want);
      console.log(`wrote ${f}`);
    }
  }
  if (drift) process.exit(1);
}
